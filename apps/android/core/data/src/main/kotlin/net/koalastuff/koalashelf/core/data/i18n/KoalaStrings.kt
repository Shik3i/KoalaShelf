fun stringsForLocale(locale: AppLocale): KoalaStrings {
    return when (locale) {
        AppLocale.DE -> DeKoalaStrings
        AppLocale.EN -> EnKoalaStrings
        AppLocale.SYSTEM -> {
            val lang = Locale.getDefault().language.lowercase()
            if (lang.startsWith("de")) DeKoalaStrings else EnKoalaStrings
        }
    }
}

val LocalKoalaStrings = staticCompositionLocalOf { DeKoalaStrings }

val currentKoalaStrings: KoalaStrings
    @Composable
    @ReadOnlyComposable
    get() = LocalKoalaStrings.current
