// Builds KoalaShelf design tokens from tokens/*.json (DTCG) into CSS, TypeScript and Kotlin.
// Fails when a required contrast pair drops below its WCAG threshold.
import StyleDictionary from 'style-dictionary';

const HEADER = 'Generated by packages/design-tokens. Do not edit by hand.';
const ANDROID_PKG = 'net.koalastuff.koalashelf.core.designsystem';
const ANDROID_DIR = `../../apps/android/core/designsystem/src/main/kotlin/${ANDROID_PKG.replaceAll('.', '/')}/`;

// [foreground, background, minimum ratio]. 4.5 for text, 3 for large text / UI parts.
const CONTRAST_PAIRS = [
  ['ink', 'bg', 4.5],
  ['ink', 'card', 4.5],
  ['ink', 'panel', 4.5],
  ['muted', 'bg', 4.5],
  ['muted', 'card', 4.5],
  ['on-accent', 'accent', 4.5],
  ['ctrl-ink', 'ctrl', 4.5],
  ['sel-ink', 'sel', 4.5],
  ['cur-ink', 'cur-bg', 4.5],
  ['accent', 'bg', 3],
  ['accent', 'card', 3]
];

const val = (t) => t.$value ?? t.value;

/** Splits tokens into theme colors and everything else. */
function split(dictionary) {
  const themes = { light: {}, dark: {} };
  const rest = [];
  for (const t of dictionary.allTokens) {
    if (t.path[0] === 'c') themes[t.path[1]][t.path.slice(2).join('-')] = val(t);
    else rest.push(t);
  }
  return { themes, rest };
}

function cssValue(t) {
  const v = val(t);
  const type = t.$type ?? t.type;
  if (type === 'fontFamily') return v.map((f) => (/\s/.test(f) ? `'${f}'` : f)).join(', ');
  if (type === 'cubicBezier') return `cubic-bezier(${v.join(', ')})`;
  return String(v);
}

function luminance(hex) {
  const [r, g, b] = [1, 3, 5].map((i) => {
    const c = parseInt(hex.slice(i, i + 2), 16) / 255;
    return c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4;
  });
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}

function contrast(a, b) {
  const [hi, lo] = [luminance(a), luminance(b)].sort((x, y) => y - x);
  return (hi + 0.05) / (lo + 0.05);
}

function checkContrast(themes) {
  const failures = [];
  for (const [theme, colors] of Object.entries(themes)) {
    for (const [fg, bg, min] of CONTRAST_PAIRS) {
      const ratio = contrast(colors[fg], colors[bg]);
      if (ratio < min) failures.push(`${theme}: ${fg} on ${bg} = ${ratio.toFixed(2)} (< ${min})`);
    }
  }
  if (failures.length) throw new Error(`Contrast check failed:\n  ${failures.join('\n  ')}`);
}

const camel = (s) => s.replace(/-(\w)/g, (_, c) => c.toUpperCase());

StyleDictionary.registerFormat({
  name: 'koala/css',
  format: ({ dictionary }) => {
    const { themes, rest } = split(dictionary);
    checkContrast(themes);
    const vars = (obj) =>
      Object.entries(obj)
        .map(([k, v]) => `  --c-${k}: ${v};`)
        .join('\n');
    const base = rest.map((t) => `  --${t.path.join('-')}: ${cssValue(t)};`).join('\n');
    return `/* ${HEADER} */
:root {
${base}
}

:root,
.th-light {
  color-scheme: light;
${vars(themes.light)}
}

.th-dark {
  color-scheme: dark;
${vars(themes.dark)}
}

@media (prefers-color-scheme: dark) {
  :root:not(.th-light) {
    color-scheme: dark;
${vars(themes.dark).replaceAll('  --', '    --')}
  }
}
`;
  }
});

StyleDictionary.registerFormat({
  name: 'koala/ts',
  format: ({ dictionary }) => {
    const { themes, rest } = split(dictionary);
    const base = {};
    for (const t of rest) {
      (base[t.path[0]] ??= {})[t.path.slice(1).join('-')] = val(t);
    }
    return `// ${HEADER}
export const colors = ${JSON.stringify(themes, null, 2)} as const;

export const tokens = ${JSON.stringify(base, null, 2)} as const;

export type Theme = keyof typeof colors;
export type ColorName = keyof typeof colors.light;
`;
  }
});

StyleDictionary.registerFormat({
  name: 'koala/kotlin',
  format: ({ dictionary }) => {
    const { themes, rest } = split(dictionary);
    const names = Object.keys(themes.light);
    const argb = (hex) => `Color(0xFF${hex.slice(1).toUpperCase()})`;
    const instance = (name, colors) =>
      `val ${name} = KoalaColors(\n${names.map((n) => `    ${camel(n)} = ${argb(colors[n])},`).join('\n')}\n)`;
    const group = (prefix, unit, label = (k) => camel(k)) =>
      rest
        .filter((t) => t.path[0] === prefix && /^\d+(\.\d+)?px$/.test(val(t)))
        .map((t) => `    val ${label(t.path.slice(1).join('-'))} = ${parseFloat(val(t))}.${unit}`)
        .join('\n');
    const motion = Object.fromEntries(rest.filter((t) => t.path[0] === 'motion').map((t) => [t.path[1], val(t)]));
    return `// ${HEADER}
package ${ANDROID_PKG}

import androidx.compose.runtime.Immutable
import androidx.compose.ui.graphics.Color
import androidx.compose.ui.unit.dp
import androidx.compose.ui.unit.sp

@Immutable
data class KoalaColors(
${names.map((n) => `    val ${camel(n)}: Color,`).join('\n')}
)

${instance('LightKoalaColors', themes.light)}

${instance('DarkKoalaColors', themes.dark)}

object KoalaTypeScale {
${group('fs', 'sp', (k) => (/^\d/.test(k) ? `size${k}` : camel(k)))}
}

object KoalaSpacing {
${group('sp', 'dp', (k) => `s${k}`)}
}

object KoalaRadius {
${group('r', 'dp')}
}

object KoalaLayout {
${group('layout', 'dp')}
}

object KoalaMotion {
    const val SPIN_MS = ${parseFloat(motion.spin) * 1000}
    const val FAST_MS = ${parseFloat(motion.fast)}
    const val BASE_MS = ${parseFloat(motion.base)}
    const val TONEARM_BASE_DEG = ${motion['tonearm-base']}f
    const val TONEARM_RANGE_DEG = ${motion['tonearm-range']}f
}
`;
  }
});

const sd = new StyleDictionary({
  source: ['tokens/**/*.json'],
  usesDtcg: true,
  log: { verbosity: 'default' },
  platforms: {
    web: {
      transforms: ['name/kebab'],
      buildPath: 'dist/',
      files: [
        { destination: 'tokens.css', format: 'koala/css' },
        { destination: 'tokens.ts', format: 'koala/ts' }
      ]
    },
    android: {
      transforms: ['name/kebab'],
      buildPath: ANDROID_DIR,
      files: [{ destination: 'KoalaTokens.kt', format: 'koala/kotlin' }]
    }
  }
});

await sd.buildAllPlatforms();
